import sys; sys.path.insert(0, ".")
from lrcdf import params as P
lines = ["-- Generated by scripts/gen_neutral.py: the neutral value of every setting the model controls.", "return {", "    WhiteBalance = 'As Shot',"]
for name, default in zip(P.SCALAR_NAMES, P.SCALAR_DEFAULTS):
    lines.append(f"    {name} = {float(default):g},")
for tag in P.CURVES:
    lines.append(f"    {tag} = {{ 0, 0, 255, 255 }},")
for name, default in P.EXTRA.items():
    lines.append(f"    {name} = {default:g},")
lines.append("}")
open("plugin/LRCDFAuto.lrplugin/Neutral.lua", "w").write("\n".join(lines) + "\n")
